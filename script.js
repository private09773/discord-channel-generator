function update() {
    const input = document.getElementById('input').value;
    const font = document.getElementById('fontSelect').value;
    const sep = document.getElementById('sepSelect').value;
    
    // Convert the text based on the selected font map
    const converted = input.split('').map(char => maps[font][char] || char).join('');
    
    // Update the output display
    document.getElementById('output').innerText = `${sep} ${converted} ${sep}`;
}

function copyText() {
    const textToCopy = document.getElementById('output').innerText;
    navigator.clipboard.writeText(textToCopy).then(() => {
        // Optional: Add a small visual feedback if you want
        alert("Copied: " + textToCopy);
    });
}
